-- Raw stock: balance/value come from the actual batches (the single stock truth).
-- avg_cost = average cost of batches still in hand (falls back to opening/purchase
-- average when nothing is left). used_qty comes from the production usage ledger.
CREATE OR REPLACE VIEW public.v_raw_stock WITH (security_invoker=true) AS
SELECT id, code, name, unit, opening_stock, opening_unit_cost, reorder_level,
  purchased_qty, purchase_value, avg_cost, used_qty, damaged_qty,
  batch_remaining AS balance, batch_value AS stock_value, damage_value AS damage_loss,
  CASE WHEN reorder_level IS NULL THEN 'Set level' WHEN batch_remaining <= reorder_level THEN 'LOW' ELSE 'OK' END AS status
FROM (
  SELECT r.id, r.code, r.name, r.unit, r.opening_stock, r.opening_unit_cost, r.reorder_level,
    COALESCE(p.qty,0::numeric) AS purchased_qty, COALESCE(p.val,0::numeric) AS purchase_value,
    CASE WHEN COALESCE(b.rem,0::numeric) > 0 THEN COALESCE(b.val,0::numeric) / b.rem
         WHEN (r.opening_stock + COALESCE(p.qty,0::numeric)) = 0 THEN r.opening_unit_cost
         ELSE ((r.opening_stock * r.opening_unit_cost) + COALESCE(p.val,0::numeric)) / (r.opening_stock + COALESCE(p.qty,0::numeric)) END AS avg_cost,
    COALESCE(u.qty,0::numeric) AS used_qty, COALESCE(d.qty,0::numeric) AS damaged_qty,
    COALESCE(b.rem,0::numeric) AS batch_remaining, COALESCE(b.val,0::numeric) AS batch_value,
    COALESCE(d.val,0::numeric) AS damage_value
  FROM raw_materials r
  LEFT JOIN (SELECT purchases.raw_material_id, sum(purchases.qty) AS qty, sum(purchases.qty * purchases.unit_cost) AS val FROM purchases GROUP BY purchases.raw_material_id) p ON p.raw_material_id = r.id
  LEFT JOIN (SELECT production_batch_usage.raw_material_id, sum(production_batch_usage.qty_used) AS qty FROM production_batch_usage GROUP BY production_batch_usage.raw_material_id) u ON u.raw_material_id = r.id
  LEFT JOIN (SELECT damages.raw_material_id, sum(damages.qty) AS qty, sum(damages.qty * damages.unit_cost_at_time) AS val FROM damages WHERE damages.damage_type = 'Raw Material' GROUP BY damages.raw_material_id) d ON d.raw_material_id = r.id
  LEFT JOIN (SELECT raw_material_batches.raw_material_id, sum(raw_material_batches.qty_remaining) AS rem, sum(raw_material_batches.qty_remaining * raw_material_batches.unit_cost) AS val FROM raw_material_batches GROUP BY raw_material_batches.raw_material_id) b ON b.raw_material_id = r.id
) s;

-- Estimated current cost of one bundle (recipe x current batch costs). Display only:
-- profit never uses this; it uses invoice_lines.cogs_amount locked at sale time.
CREATE OR REPLACE VIEW public.v_product_cost WITH (security_invoker=true) AS
SELECT rc.product_id, sum(rc.qty_per_bundle * rs.avg_cost) AS std_cost
FROM recipe rc JOIN v_raw_stock rs ON rs.id = rc.raw_material_id
GROUP BY rc.product_id;

-- Finished stock: balance/value come from production batches still in hand;
-- cogs is the sum of the actual costs locked into invoice lines.
CREATE OR REPLACE VIEW public.v_product_stock WITH (security_invoker=true) AS
SELECT id, code, name, opening_stock, min_stock, produced, sold, gross_sales, damaged, std_cost,
  fg_remaining AS balance, fg_value AS stock_value, cogs_amount AS cogs, damage_value AS damage_loss,
  CASE WHEN sold = 0::numeric THEN 0::numeric ELSE gross_sales / sold END AS avg_rate,
  CASE WHEN min_stock IS NULL THEN 'Set level' WHEN fg_remaining <= min_stock THEN 'LOW' ELSE 'OK' END AS status
FROM (
  SELECT p.id, p.code, p.name, p.opening_stock, p.min_stock,
    COALESCE(pr.qty,0::numeric) AS produced, COALESCE(s.qty,0::numeric) AS sold,
    COALESCE(s.gross,0::numeric) AS gross_sales, COALESCE(d.qty,0::numeric) AS damaged,
    COALESCE(c.std_cost,0::numeric) AS std_cost, COALESCE(pr.rem,0::numeric) AS fg_remaining,
    COALESCE(pr.val,0::numeric) AS fg_value, COALESCE(s.cogs,0::numeric) AS cogs_amount,
    COALESCE(d.val,0::numeric) AS damage_value
  FROM products p
  LEFT JOIN (SELECT production.product_id, sum(production.bundles) AS qty, sum(production.qty_remaining) AS rem, sum(production.qty_remaining * (production.total_cost / NULLIF(production.bundles,0::numeric))) AS val FROM production GROUP BY production.product_id) pr ON pr.product_id = p.id
  LEFT JOIN (SELECT invoice_lines.product_id, sum(invoice_lines.qty) AS qty, sum(invoice_lines.qty * invoice_lines.unit_rate) AS gross, sum(invoice_lines.cogs_amount) AS cogs FROM invoice_lines GROUP BY invoice_lines.product_id) s ON s.product_id = p.id
  LEFT JOIN (SELECT damages.product_id, sum(damages.qty) AS qty, sum(damages.qty * damages.unit_cost_at_time) AS val FROM damages WHERE damages.damage_type = 'Finished Goods' GROUP BY damages.product_id) d ON d.product_id = p.id
  LEFT JOIN v_product_cost c ON c.product_id = p.id
) s;

CREATE OR REPLACE VIEW public.v_invoice_summary WITH (security_invoker=true) AS
SELECT id, invoice_no, invoice_date, customer_id, customer_name, invoice_discount, gross, line_discounts, received,
  gross - line_discounts - invoice_discount AS net_amount,
  gross - line_discounts - invoice_discount - received AS balance_due,
  CASE WHEN (gross - line_discounts - invoice_discount - received) <= 0::numeric THEN 'Paid'::text
       WHEN received > 0::numeric THEN 'Partial'::text ELSE 'Unpaid'::text END AS status
FROM (
  SELECT i.id, i.invoice_no, i.invoice_date, i.customer_id, c.name AS customer_name, i.invoice_discount,
    COALESCE(l.gross,0::numeric) AS gross, COALESCE(l.disc,0::numeric) AS line_discounts, COALESCE(pm.amt,0::numeric) AS received
  FROM invoices i JOIN customers c ON c.id = i.customer_id
  LEFT JOIN (SELECT invoice_lines.invoice_id, sum(invoice_lines.qty * invoice_lines.unit_rate) AS gross, sum(invoice_lines.line_discount) AS disc FROM invoice_lines GROUP BY invoice_lines.invoice_id) l ON l.invoice_id = i.id
  LEFT JOIN (SELECT payments.invoice_id, sum(payments.amount) AS amt FROM payments GROUP BY payments.invoice_id) pm ON pm.invoice_id = i.id
) b;

CREATE OR REPLACE VIEW public.v_sale_order_summary WITH (security_invoker=true) AS
SELECT o.id, o.order_no, o.order_date, o.delivery_date, o.customer_id, c.name AS customer_name,
  o.order_discount, o.notes, o.status, o.invoice_id,
  COALESCE(l.gross,0::numeric) AS gross, COALESCE(l.disc,0::numeric) AS line_discounts,
  COALESCE(l.gross,0::numeric) - COALESCE(l.disc,0::numeric) - o.order_discount AS net_amount
FROM sale_orders o JOIN customers c ON c.id = o.customer_id
LEFT JOIN (SELECT sale_order_lines.order_id, sum(sale_order_lines.qty * sale_order_lines.unit_rate) AS gross, sum(sale_order_lines.line_discount) AS disc FROM sale_order_lines GROUP BY sale_order_lines.order_id) l ON l.order_id = o.id;

-- Profit & Loss. COGS = actual batch costs locked into invoice_lines.cogs_amount
-- at sale time (the same numbers shown per-invoice), never recomputed.
CREATE OR REPLACE VIEW public.v_pnl WITH (security_invoker=true) AS
SELECT gross_sales, discounts, (gross_sales - discounts) AS net_sales, cogs, damage_loss,
  operating_expenses, owner_draws, ((gross_sales - discounts) - cogs) AS gross_margin,
  ((((gross_sales - discounts) - cogs) - damage_loss) - operating_expenses) AS operating_net_profit,
  (((((gross_sales - discounts) - cogs) - damage_loss) - operating_expenses) - owner_draws) AS net_retained_profit
FROM (
  SELECT COALESCE((SELECT sum(invoice_lines.qty * invoice_lines.unit_rate) FROM invoice_lines),0::numeric) AS gross_sales,
    (COALESCE((SELECT sum(invoice_lines.line_discount) FROM invoice_lines),0::numeric) + COALESCE((SELECT sum(invoices.invoice_discount) FROM invoices),0::numeric)) AS discounts,
    COALESCE((SELECT sum(invoice_lines.cogs_amount) FROM invoice_lines),0::numeric) AS cogs,
    COALESCE((SELECT sum(damages.qty * damages.unit_cost_at_time) FROM damages),0::numeric) AS damage_loss,
    COALESCE((SELECT sum(expenses.amount) FROM expenses WHERE expenses.type = 'OPERATING'),0::numeric) AS operating_expenses,
    COALESCE((SELECT sum(expenses.amount) FROM expenses WHERE expenses.type = 'OWNER DRAW'),0::numeric) AS owner_draws
) g;

