-- Exported / rebuilt 2026-11-01 from the live Supabase project "orca water".
--
-- HOW TO RESTORE INTO A FRESH SUPABASE PROJECT:
--   1. Create a new Supabase project.
--   2. Open SQL Editor, paste this whole file, run it once.
--   3. In Streamlit (Manage App -> Settings -> Secrets) set:
--        SUPABASE_URL = https://<your-project-ref>.supabase.co
--        SUPABASE_SERVICE_KEY = <service_role / secret key>  (server-side only!)
--        APP_PASSWORD = <your app login password>
--   The older secret name SUPABASE_KEY is also accepted by the app.
--
-- SECURITY MODEL (intentional): the app runs only on the server behind APP_PASSWORD.
-- RLS is enabled with NO policies and the public anon/authenticated roles have NO
-- grants at all, so public (anon/publishable) keys can access nothing. Only the
-- service_role/secret key - which must live solely in Streamlit server secrets -
-- can read/write. Supabase Auth sign-up is disabled (Auth is not used by the app).
